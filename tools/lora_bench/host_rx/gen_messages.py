"""Pull the LoRa message classes (and the AudioBeep / TXProgress ones the processors touch)
out of the real firmware/common/message.hpp, so the host build uses the same layouts."""
import re, sys
src = open(sys.argv[1]).read()
out = []
for name in ("AudioBeepMessage", "TXProgressMessage", "LoRaConfigureMessage", "LoRaPacketMessage", "LoRaRxStatusMessage"):
    m = re.search(r"\nclass " + name + r" : public Message \{.*?\n\};\n", src, re.S)
    if not m:
        sys.exit("missing " + name)
    out.append(m.group(0))
open(sys.argv[2], "w").write("// generated by gen_messages.py from firmware/common/message.hpp\n" + "".join(out))
